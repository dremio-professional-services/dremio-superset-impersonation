"""Helpers for the browser tests.

UI helpers drive the Superset and Dremio web UIs. Setup helpers (marked
"(setup)") prepare test data through REST APIs: datasets, charts, dashboard,
PATs. They are not what the tests check.
"""

from __future__ import annotations

import itertools
import json
import re
import uuid
from pathlib import Path

import requests
from playwright.sync_api import Browser, Page, expect

SUPERSET = "http://superset:8088"
DREMIO = "https://dremio:9047"
CA = "/run/dremio/ca.pem"
CREDS = Path("/state/credentials.json")
PROXY = "superset_proxy"
TIMEOUT_MS = 30_000
HTTP_TIMEOUT = 60
VIEWPORT = {"width": 1400, "height": 900}
DAY_MS = 24 * 3600 * 1000
# Pages opened during the current test, screenshotted at its end (conftest.py).
_pages: list[tuple[str, Page]] = []
_screenshot_numbers = itertools.count(1)  # running number over the whole run


def creds() -> dict[str, str]:
    """Return the credentials generated by the bootstrap."""
    return json.loads(CREDS.read_text())


# --------------------------------------------------------------------- UI


def new_page(browser: Browser, label: str) -> Page:
    """Open a page in a fresh browser context and remember it for screenshots."""
    page = browser.new_context(viewport=VIEWPORT).new_page()
    _pages.append((label, page))
    return page


def save_screenshots(directory: Path, test_name: str) -> None:
    """Screenshot the current test's pages that are still open, then forget them.

    Files are named ``<running number>-<test>-<page>.png``. Pages where a PAT
    was typed are closed by the test before, so they never appear on a
    screenshot.
    """
    for label, page in _pages:
        if not page.is_closed():
            number = next(_screenshot_numbers)
            page.screenshot(
                path=directory / f"{number:03d}-{test_name}-{label}.png",
                full_page=True,
            )
    _pages.clear()


def login(browser: Browser, user: str, password: str) -> Page:
    """Log in through the Superset login form in a fresh browser context."""
    page = new_page(browser, f"superset-{user}")
    page.goto(f"{SUPERSET}/login/")
    page.locator("input[type=text]").fill(user)
    page.locator("input[type=password]").fill(password)
    page.get_by_role("button", name="Sign in").click()
    page.wait_for_url(re.compile(r".*/superset/welcome/.*"))
    return page


def run_sql(page: Page, sql: str) -> None:
    """Open a fresh SQL Lab tab on the Dremio database, type SQL, press Run."""
    page.goto(f"{SUPERSET}/sqllab/?dbid={db_id()}&new=true")
    page.locator(".ace_editor").last.click()
    page.keyboard.press("ControlOrMeta+a")
    page.keyboard.press("Delete")
    page.keyboard.type(sql)
    page.get_by_role("button", name="Run").click()


def dremio_ui_job_user(browser: Browser, marker: str) -> str:
    """Return the job owner shown in the Dremio UI for the job with ``marker``.

    Logs in to the Dremio web UI as admin, searches the job by its SQL marker
    on the Jobs page, opens the job profile (Overview) and reads "User:".
    """
    page = new_page(browser, "dremio-job-profile")
    page.goto(f"{DREMIO}/")
    page.locator("#userName").fill("dremio_admin")
    page.locator("#password").fill(creds()["dremio_admin"])
    page.get_by_role("button", name="Log In").click()
    page.wait_for_load_state("networkidle")
    page.goto(f"{DREMIO}/jobs")
    page.get_by_placeholder("Search jobs").fill(marker)
    rows = page.get_by_role("row").filter(has_text="execute prepared statement")
    expect(rows.first).to_be_visible(timeout=TIMEOUT_MS)
    rows.first.locator("a").first.click()
    expect(page.get_by_text(marker).first).to_be_visible(timeout=TIMEOUT_MS)
    summary = page.get_by_text("Summary", exact=True).locator("xpath=..").inner_text()
    found = re.search(r"User:\s*(\S+)", summary)
    if found is None:
        msg = "no 'User:' on the Dremio job profile"
        raise LookupError(msg)
    return found.group(1)


def marker() -> str:
    """Return a unique string to find a query in Dremio's job list."""
    return f"m{uuid.uuid4().hex[:12]}"


# ------------------------------------------------------------------ SETUP


def api(user: str) -> requests.Session:
    """Return a Superset REST session logged in as ``user``."""
    session = requests.Session()
    resp = session.post(
        f"{SUPERSET}/api/v1/security/login",
        json={
            "username": user,
            "password": creds()[user],
            "provider": "db",
            "refresh": False,
        },
        timeout=HTTP_TIMEOUT,
    )
    resp.raise_for_status()
    session.headers["Authorization"] = f"Bearer {resp.json()['access_token']}"
    return session


def db_id() -> int:
    """Return the id of the Superset database "Dremio"."""
    resp = api("admin").get(f"{SUPERSET}/api/v1/database/", timeout=HTTP_TIMEOUT)
    return next(
        d["id"] for d in resp.json()["result"] if d["database_name"] == "Dremio"
    )


def _filter(column: str, value: str) -> dict[str, str]:
    """Return a Superset list-API filter for ``column == value``."""
    return {
        "q": json.dumps({"filters": [{"col": column, "opr": "eq", "value": value}]}),
    }


def ensure_chart(name: str, sql: str, columns: list[str]) -> int:
    """Return a table chart on a virtual dataset, created once as alice (setup)."""
    session = api("alice")  # dataset creation reads columns, so it runs a query
    found = session.get(
        f"{SUPERSET}/api/v1/chart/",
        params=_filter("slice_name", name),
        timeout=HTTP_TIMEOUT,
    ).json()
    if found["count"]:
        return found["result"][0]["id"]
    resp = session.post(
        f"{SUPERSET}/api/v1/dataset/",
        json={
            "database": db_id(),
            "table_name": f"ds_{name}",
            "sql": sql,
            "schema": None,
        },
        timeout=HTTP_TIMEOUT,
    )
    resp.raise_for_status()
    dataset = resp.json()["id"]
    params = {
        "viz_type": "table",
        "datasource": f"{dataset}__table",
        "query_mode": "raw",
        "all_columns": columns,
        "row_limit": 100,
    }
    resp = session.post(
        f"{SUPERSET}/api/v1/chart/",
        json={
            "slice_name": name,
            "viz_type": "table",
            "datasource_id": dataset,
            "datasource_type": "table",
            "params": json.dumps(params),
        },
        timeout=HTTP_TIMEOUT,
    )
    resp.raise_for_status()
    return resp.json()["id"]


def ensure_dashboard(title: str, chart_id: int) -> int:
    """Return a dashboard containing one chart, created once as alice (setup)."""
    session = api("alice")
    found = session.get(
        f"{SUPERSET}/api/v1/dashboard/",
        params=_filter("dashboard_title", title),
        timeout=HTTP_TIMEOUT,
    ).json()
    if found["count"]:
        return found["result"][0]["id"]
    resp = session.post(
        f"{SUPERSET}/api/v1/dashboard/",
        json={"dashboard_title": title, "published": True},
        timeout=HTTP_TIMEOUT,
    )
    resp.raise_for_status()
    dashboard = resp.json()["id"]
    session.put(
        f"{SUPERSET}/api/v1/chart/{chart_id}",
        json={"dashboards": [dashboard]},
        timeout=HTTP_TIMEOUT,
    ).raise_for_status()
    return dashboard


def _dremio_session(user: str, password: str) -> requests.Session:
    """Return a Dremio REST session logged in as ``user``."""
    session = requests.Session()
    session.verify = CA
    token = session.post(
        f"{DREMIO}/apiv2/login",
        json={"userName": user, "password": password},
        timeout=HTTP_TIMEOUT,
    ).json()["token"]
    session.headers["Authorization"] = f"_dremio{token}"
    return session


def _proxy_user_id(session: requests.Session) -> str:
    """Return the Dremio id of the proxy user."""
    return session.get(
        f"{DREMIO}/api/v3/user/by-name/{PROXY}",
        timeout=HTTP_TIMEOUT,
    ).json()["id"]


def new_proxy_pat(ms_to_expire: int = DAY_MS) -> str:
    """Create a new PAT as the proxy user in Dremio (setup)."""
    session = _dremio_session(PROXY, creds()[PROXY])
    resp = session.post(
        f"{DREMIO}/api/v3/user/{_proxy_user_id(session)}/token",
        json={
            "label": f"ui-{uuid.uuid4().hex[:8]}",
            "millisecondsToExpire": ms_to_expire,
        },
        timeout=HTTP_TIMEOUT,
    )
    resp.raise_for_status()
    return resp.text.strip().strip('"')


def revoke_proxy_pats() -> None:
    """Revoke all PATs of the proxy user in Dremio (setup)."""
    session = _dremio_session(PROXY, creds()[PROXY])
    session.delete(
        f"{DREMIO}/api/v3/user/{_proxy_user_id(session)}/token",
        timeout=HTTP_TIMEOUT,
    ).raise_for_status()
