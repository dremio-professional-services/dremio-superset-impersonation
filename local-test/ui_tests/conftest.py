"""Fixtures for the browser tests (Playwright) against the running local stack.

Everything under test goes through the Superset web UI in a real Chromium; the
Dremio job owner is read in the Dremio web UI. Helpers are in ``helpers.py``.
At the end of every test, its open pages are saved as screenshots (location
and naming: CONTRIBUTING.md, "Local test environment").
"""

from __future__ import annotations

import re
import shutil
from pathlib import Path
from typing import TYPE_CHECKING

import pytest

from .helpers import creds, save_screenshots

if TYPE_CHECKING:
    from collections.abc import Iterator

SCREENSHOTS = Path("/artifacts/screenshots")


@pytest.fixture(scope="session")
def c() -> dict[str, str]:
    """Return the credentials generated by the bootstrap."""
    return creds()


@pytest.fixture(scope="session", autouse=True)
def fresh_screenshot_directory() -> None:
    """Remove the screenshots of the previous run."""
    shutil.rmtree(SCREENSHOTS, ignore_errors=True)
    SCREENSHOTS.mkdir(parents=True)


@pytest.fixture(autouse=True)
def screenshots(request: pytest.FixtureRequest) -> Iterator[None]:
    """Save screenshots of the test's open pages after the test."""
    yield
    save_screenshots(SCREENSHOTS, screenshot_name(request.node.name))


def screenshot_name(node_name: str) -> str:
    """Turn ``test_x[chromium-alice-first]`` into ``x-alice-first``."""
    name = node_name.removeprefix("test_").replace("[chromium", "[")
    return re.sub(r"[^\w.]+", "-", name).strip("-")
